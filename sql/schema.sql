-- Canonical logical schema for MySQL 8+. The Python pipeline creates the table
-- from the source DataFrame types so it can also run locally with SQLite.
CREATE TABLE IF NOT EXISTS ev_vehicles (
    vehicle_id VARCHAR(32) NOT NULL PRIMARY KEY,
    model_name VARCHAR(255),
    manufacturer VARCHAR(150),
    model_year SMALLINT,
    manufacturing_country VARCHAR(100),
    market_region VARCHAR(100),
    category VARCHAR(100),
    battery_capacity_kwh DECIMAL(10,2),
    battery_type VARCHAR(80),
    battery_cycle_life DECIMAL(12,2),
    battery_degradation_pct_5yr DECIMAL(8,3),
    range_km DECIMAL(10,2),
    efficiency_wh_per_km DECIMAL(10,2),
    motor_power_kw DECIMAL(10,2),
    torque_nm DECIMAL(10,2),
    num_motors SMALLINT,
    drivetrain VARCHAR(80),
    top_speed_kmph DECIMAL(10,2),
    acceleration_0_100_sec DECIMAL(10,2),
    max_dc_charging_kw DECIMAL(10,2),
    charging_dc_fast_time_min DECIMAL(10,2),
    charging_ac_time_hr DECIMAL(10,2),
    num_charging_ports SMALLINT,
    num_seats SMALLINT,
    weight_kg DECIMAL(10,2),
    cargo_capacity_liters DECIMAL(10,2),
    price_usd DECIMAL(14,2),
    insurance_cost_usd_yearly DECIMAL(12,2),
    warranty_years SMALLINT,
    resale_value_pct_3yr DECIMAL(8,3),
    safety_rating_stars SMALLINT,
    autonomous_level SMALLINT,
    infotainment_screen_inch DECIMAL(6,2),
    co2_saved_tons_per_year DECIMAL(12,3),
    annual_sales_units DECIMAL(14,2),
    customer_rating DECIMAL(4,2),
    recommended_use_case VARCHAR(150),
    source_split VARCHAR(10),
    efficiency_kwh_per_100km DECIMAL(10,3),
    INDEX idx_ev_manufacturer (manufacturer),
    INDEX idx_ev_year (model_year),
    INDEX idx_ev_category (category),
    INDEX idx_ev_battery_type (battery_type),
    INDEX idx_ev_region (market_region)
);
